def render_map(path:Path,title:str,branches:Dict[str,List[str]]):
    dot=Digraph('G',format='png')
    dot.attr(rankdir='TB',bgcolor='white',margin='0.02',pad='0.05',nodesep='0.20',ranksep='0.34',dpi='180')
    dot.attr('node',shape='box',style='rounded,filled',fontname='Noto Sans CJK SC',fontsize='11',color='#8296A8',penwidth='1.0',fillcolor='#FAFBFC',margin='0.10,0.06')
    dot.attr('edge',color='#9AAAB8',arrowsize='0.52',penwidth='0.9')
    dot.node('root',title,fillcolor='#E6F1F8',color='#527A95',fontsize='14',penwidth='1.3')
    for i,(b,leaves) in enumerate(branches.items(),1):
        bid=f'b{i}'; dot.node(bid,b,fillcolor='#EEF5F1',color='#6B8E7A',fontsize='12'); dot.edge('root',bid)
        for j,leaf in enumerate(leaves,1):
            nid=f'{bid}_{j}'; dot.node(nid,leaf,fillcolor='white',color='#B2BDC7',fontsize='10'); dot.edge(bid,nid)
    base=str(path.with_suffix('')); dot.render(base,cleanup=True)
    gen=Path(base+'.png')
    if gen!=path: shutil.move(gen,path)

