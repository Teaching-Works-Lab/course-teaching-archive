def cleanup_unused_media(docx_path:Path):
    # Remove unreferenced image relationships/media inherited from reference lesson tables while preserving the school logo.
    from lxml import etree
    with zipfile.ZipFile(docx_path,'r') as zin:
        members={n:zin.read(n) for n in zin.namelist()}
    nsr={'r':'http://schemas.openxmlformats.org/officeDocument/2006/relationships'}
    nsp={'pr':'http://schemas.openxmlformats.org/package/2006/relationships'}
    docxml=etree.fromstring(members['word/document.xml'])
    used=set(docxml.xpath('//@r:embed | //@r:link | //@r:id',namespaces=nsr))
    relname='word/_rels/document.xml.rels'; relxml=etree.fromstring(members[relname]); removed=[]
    for rel in list(relxml.xpath('//pr:Relationship',namespaces=nsp)):
        if rel.get('Type','').endswith('/image') and rel.get('Id') not in used:
            removed.append(rel.get('Target')); rel.getparent().remove(rel)
    members[relname]=etree.tostring(relxml,xml_declaration=True,encoding='UTF-8',standalone='yes')
    remaining=set()
    for name,data in list(members.items()):
        if name.endswith('.rels'):
            try:
                rx=etree.fromstring(data)
                for rel in rx.xpath('//pr:Relationship',namespaces=nsp):
                    targ=rel.get('Target','')
                    if targ.startswith('media/'): remaining.add('word/'+targ)
                    elif targ.startswith('../media/'): remaining.add('word/media/'+targ.split('../media/',1)[1])
            except: pass
    for targ in removed:
        media='word/'+targ if targ.startswith('media/') else None
        if media and media not in remaining: members.pop(media,None)
    tmp=docx_path.with_suffix('.cleaning.docx')
    with zipfile.ZipFile(tmp,'w',zipfile.ZIP_DEFLATED) as zout:
        for n,d in members.items(): zout.writestr(n,d)
    tmp.replace(docx_path)

def sha256(p:Path):
    h=hashlib.sha256()
    with p.open('rb') as f:
        for c in iter(lambda:f.read(1<<20),b''): h.update(c)
    return h.hexdigest()

