def process_md(l):
    if l['kind']=='理论':
        stages=[('一、核心机理与工艺结构讲解',25),('二、参数/案例分析与学生推演',25),('三、独立产出、互审与证据复盘',20)]
    else:
        stages=[('一、安全检查与实验设计确认',15),('二、分组实验/样件与数据采集',35),('三、数据复核、质量分析与证据固化',20)]
    chunks=[]
    for (head,mins),(title,detail) in zip(stages,l['blocks']):
        chunks.append(f'**{head}（约{mins} min）—{title}**\n\n【教师】{detail}\n\n【学生】按任务约束完成分析/实验，保存中间结果并说明判断依据；教师只提示定位方法、边界与验收条件，不代替学生完成核心产物。')
    chunks.append(f'【课堂产物】{l["product"]}')
    chunks.append(f'【学习证据】{l["evidence"]}')
    chunks.append(f'【评价关联】{l["assess"]}')
    return '\n\n'.join(chunks)

