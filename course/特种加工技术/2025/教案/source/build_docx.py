# ---------- map render ----------
def render_map(path:Path,title:str,branches:dict[str,list[str]]):
    dot=Digraph('G',format='png')
    dot.attr(rankdir='TB',bgcolor='white',margin='0.02',pad='0.04',nodesep='0.2',ranksep='0.34',dpi='190')
    dot.attr('node',shape='box',style='rounded,filled',fontname='Noto Sans CJK SC',fontsize='10.5',color='#6B7280',penwidth='1.0',fillcolor='#F8FAFC',margin='0.09,0.05')
    dot.attr('edge',color='#94A3B8',arrowsize='0.5',penwidth='0.9')
    dot.node('root',title,fillcolor='#E6F1F8',color='#2F6F8F',fontsize='13.5',penwidth='1.4')
    for bi,(b,leaves) in enumerate(branches.items(),1):
        bn=f'b{bi}'; dot.node(bn,b,fillcolor='#EEF6F1',color='#5D846E',fontsize='11.5'); dot.edge('root',bn)
        for li,leaf in enumerate(leaves,1):
            ln=f'{bn}_{li}'; dot.node(ln,leaf,fillcolor='white',color='#A5B4C2',fontsize='9.5'); dot.edge(bn,ln)
    out=str(path.with_suffix('')); dot.render(out,cleanup=True)
    gen=Path(out+'.png')
    if gen!=path: shutil.move(gen,path)

