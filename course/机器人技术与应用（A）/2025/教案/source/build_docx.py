# Markup cleaner from MD sections to plain Word text
def clean_md(s):
    s=re.sub(r'!\[[^\]]*\]\([^\)]*\)','',s)
    s=s.replace('**','').replace('`','')
    s=re.sub(r'^- ','',s,flags=re.M)
    s=re.sub(r'\n{3,}','\n\n',s)
    return s.strip()

def extract_info(field_text):
    # lesson info bullets to dict
    d={}
    for line in field_text.splitlines():
        m=re.match(r'- \*\*(.+?)\*\*：(.+)',line.strip())
        if m: d[m.group(1)]=m.group(2).strip()
    return d

