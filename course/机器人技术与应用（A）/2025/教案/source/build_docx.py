def render_map(path: Path, title: str, branches: Dict[str,List[str]], course=False):
    dot=Digraph('G', format='png')
    dot.attr(rankdir='TB', bgcolor='white', margin='0.02', pad='0.05', nodesep='0.22', ranksep='0.38', dpi='190')
    dot.attr('node', shape='box', style='rounded,filled', fontname='Noto Sans CJK SC', fontsize='11', color='#6B7280', penwidth='1.0', fillcolor='#F8FAFC', margin='0.10,0.06')
    dot.attr('edge', color='#94A3B8', arrowsize='0.55', penwidth='0.9')
    root='root'; dot.node(root, title, fillcolor='#E6F1F8', color='#2F6F8F', fontsize='14', penwidth='1.4')
    for bi,(branch, leaves) in enumerate(branches.items(),1):
        b=f'b{bi}'; dot.node(b, branch, fillcolor='#EEF6F1', color='#5D846E', fontsize='12')
        dot.edge(root,b)
        for li,leaf in enumerate(leaves,1):
            n=f'{b}_{li}'; dot.node(n, leaf, fillcolor='#FFFFFF', color='#A5B4C2', fontsize='10')
            dot.edge(b,n)
    outbase=str(path.with_suffix(''))
    dot.render(outbase, cleanup=True)
    generated=Path(outbase+'.png')
    if generated != path:
        shutil.move(generated,path)

