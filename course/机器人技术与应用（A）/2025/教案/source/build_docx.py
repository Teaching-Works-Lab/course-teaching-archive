def parse_markdown(md_path: Path):
    text=md_path.read_text(encoding='utf-8')
    # Metadata from explicit lines
    meta={}
    for key,label in [('name','课程名称'),('code','课程代码'),('semester','授课学期'),('hours','总学时')]:
        m=re.search(rf'^- \*\*{re.escape(label)}\*\*：(.+)$',text,re.M)
        if m: meta[key]=m.group(1).strip()
    lesson_parts=re.split(r'(?=^## 第\d+次课\s)',text,flags=re.M)
    lesson_parts=[p for p in lesson_parts if re.match(r'^## 第\d+次课\s',p)]
    parsed=[]
    headings=['课次信息','教学目标','课程思政','专创融合','教学重难点','教学方法与用具','教学设计','课前任务','互动导入','传授新知与课堂训练','过关检测','课堂小结','作业布置','考勤','课后教学反思','本章节参考文献']
    for p in lesson_parts:
        h=re.match(r'^## 第(\d+)次课\s+(.+)$',p,re.M)
        no=int(h.group(1)); topic=h.group(2).strip()
        fields={}
        for i,hd in enumerate(headings):
            start=re.search(rf'^### {re.escape(hd)}\s*$',p,re.M)
            if not start: continue
            pos=start.end(); next_positions=[]
            for hd2 in headings[i+1:]:
                m2=re.search(rf'^### {re.escape(hd2)}\s*$',p[pos:],re.M)
                if m2: next_positions.append(pos+m2.start())
            # knowledge map image appears after 课次信息; don't swallow into it? okay, strip below.
            end=min(next_positions) if next_positions else len(p)
            val=p[pos:end].strip()
            fields[hd]=val
        img=re.search(r'!\[知识脉络图\]\((images/lesson-\d+-knowledge-map\.png)\)',p)
        fields['image']=img.group(1) if img else None
        parsed.append({'no':no,'topic':topic,'fields':fields})
    if len(parsed)!=28: raise RuntimeError(f'parsed lessons {len(parsed)} != 28')
    return meta,parsed,text

